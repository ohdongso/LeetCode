package _1_50;

public class _10_정규표현식매칭_0 {

    static class Solution {

        /*
            [문제 설명]
            문자열 s와 패턴 p가 주어졌을 때,
            패턴 p가 문자열 s 전체와 매칭되는지 여부를 반환한다.

            지원 패턴:
            '.' → 아무 문자 1개
            '*' → 바로 앞 문자를 0개 이상 반복

            예:
            "a*" → "", "a", "aa", "aaa" 모두 가능

            [핵심 아이디어 - DP]

            dp[i][j] 의미:
            문자열 s의 앞 i글자와
            정규식 p의 앞 j글자가 서로 매칭되는지 여부

            주의:
            i, j는 index가 아니라 "사용한 글자 수"이다.

            예:
            s = "aa"
            p = "a*"

            dp[0][0] → ""   vs ""
            dp[1][1] → "a"  vs "a"
            dp[2][2] → "aa" vs "a*"

            [점화식]

            1. 일반 문자 또는 '.'

               현재 문자끼리 같거나 pc가 '.'이면
               이전 상태를 그대로 따라간다.

               dp[i][j] = dp[i - 1][j - 1]

            2. '*'

               '*'는 바로 앞 문자와 한 세트이다.

               (1) 앞 문자를 0번 사용
                   → "앞 문자 + *"를 제거하는 것과 같음

                   dp[i][j] = dp[i][j - 2]

               (2) 앞 문자를 1번 이상 사용
                   → '*' 앞 문자가 현재 문자열 문자와 같거나 '.'일 때 가능

                   dp[i][j] = dp[i - 1][j]

            시간복잡도: O(m * n)
            공간복잡도: O(m * n)
         */
        public boolean isMatch(String s, String p) {

            int m = s.length(); // 입력 받은 문자열 s의 길이
            int n = p.length(); // 입력 받은 정규식 p의 길이

            /*
                문자열 s와 정규식 p의 매칭 상태를 저장하는 DP 테이블

                +1 하는 이유:
                빈 문자열("") 상태를 표현하기 위해서이다.

                dp[0][0] → "" vs ""
                dp[0][1] → "" vs p의 앞 1글자
                dp[1][0] → s의 앞 1글자 vs ""

                boolean 배열의 기본값은 false이다.
             */
            boolean[][] dp = new boolean[m + 1][n + 1];

            /*
                초기값

                빈 문자열 "" 과 빈 정규식 "" 은 서로 매칭된다.
                그래서 dp[0][0]만 true로 시작한다.

                DP는 현재 상태를 이전 상태로부터 가져오기 때문에
                시작점인 dp[0][0]이 true여야 뒤쪽으로 true가 전파될 수 있다.
             */
            dp[0][0] = true;

            /*
                [문자열 s는 비어있고, 정규식 p만 존재하는 경우 처리]

                현재 행은 0으로 고정이다.
                즉, 문자열 s는 빈 문자열("") 상태이다.

                여기서는 정규식 p만 한 글자씩 늘려가면서
                빈 문자열("")과 매칭 가능한지 확인한다.

                예:
                "" vs "a*"     → true
                "" vs "a*b*"   → true
                "" vs "a*b"    → false

                이유:
                "a*"는 a를 0번 사용할 수 있으므로 ""처럼 취급 가능하다.
                "a*b*"는 a와 b 모두 0번 사용할 수 있으므로 ""처럼 취급 가능하다.
                "a*b"는 a*는 제거 가능하지만 마지막 b는 '*'가 없어서 제거 불가능하다.

                여기서 말하는 제거 가능이란:
                실제 문자열을 삭제한다는 뜻이 아니라,
                정규식에서 "문자 + *"를 0번 사용한다고 보고
                없었던 것처럼 처리할 수 있다는 뜻이다.
             */

            /*
                [j 이해하기]

                j는 정규식 p의 실제 index가 아니라
                "정규식 앞에서부터 몇 글자를 사용했는지"를 의미한다.

                예:
                p = "a*b"

                실제 p의 index:
                index 0 = 'a'
                index 1 = '*'
                index 2 = 'b'

                DP의 열 j:
                j = 0 → ""
                j = 1 → "a"
                j = 2 → "a*"
                j = 3 → "a*b"

                따라서 j = 2라는 것은
                실제 index 2부터 본다는 뜻이 아니라,
                정규식 앞에서부터 2글자("a*")를 사용한 상태라는 뜻이다.

                문자열 index는 0부터 시작하므로
                j글자를 사용한 상태에서 현재 마지막 문자는 j - 1 위치이다.

                j = 2
                → 정규식 2글자 사용
                → 실제 포함된 index는 0, 1
                → 마지막 문자는 index 1
                → p.charAt(j - 1)

                그래서 p.charAt(j - 1)이 '*'인지 확인한다.
             */

            /*
                [왜 j = 2부터 시작하는가?]

                '*'는 단독으로 의미가 있는 문자가 아니다.
                항상 바로 앞 문자와 한 세트로 동작한다.

                예:
                a*
                b*
                .*

                따라서 최소 "문자 + *" 형태인
                2글자부터 제거 가능 여부를 확인할 수 있다.

                j = 1인 경우:
                "" vs "a"
                → 'a'는 '*'가 없으므로 제거 불가능
                → 기본값 false 그대로 유지된다.
             */

            /*
                [dp[0][j] = dp[0][j - 2] 의미]

                현재 정규식의 마지막 문자가 '*'라면
                "앞 문자 + *"를 0번 사용해서 제거할 수 있다.

                즉:
                현재 상태는
                "문자 + *" 2글자를 제거한 상태와 동일하다.

                예:
                p = "a*b*"

                dp[0][2] = dp[0][0]
                "" vs "a*"
                → "a*" 제거
                → "" vs ""

                dp[0][4] = dp[0][2]
                "" vs "a*b*"
                → 마지막 "b*" 제거
                → "" vs "a*"

                단, '*'가 있다고 무조건 true가 되는 것은 아니다.

                예:
                p = "ab*"

                dp[0][3] = dp[0][1]

                "b*"는 제거 가능하지만
                앞에 남은 "a"는 제거 불가능하다.

                따라서:
                "" vs "ab*" = false

                즉,
                현재 위치는 2칸 전 상태의 결과를 그대로 따른다.
             */
            for (int j = 2; j <= n; j++) {

                /*
                    현재 사용 중인 정규식의 마지막 문자가
                    '*'인지 확인

                    j는 사용한 글자 수이므로
                    실제 마지막 문자는 j - 1 위치이다.
                 */
                if (p.charAt(j - 1) == '*') {

                    /*
                        "문자 + *"를 0번 사용하면
                        해당 2글자를 제거 가능하다.

                        따라서 현재 상태는
                        2칸 전 상태와 동일해진다.
                     */
                    dp[0][j] = dp[0][j - 2];
                }
            }

            /*
                이제 문자열 s와 정규식 p를 본격적으로 비교한다.

                i = 문자열 s에서 사용한 글자 수
                j = 정규식 p에서 사용한 글자 수

                여기서는 문자열이 빈 상태가 아니므로
                i는 1부터 시작한다.

                정규식은 첫 글자부터 비교해야 하므로
                j도 1부터 시작한다.
             */
            for (int i = 1; i <= m; i++) {
                for (int j = 1; j <= n; j++) {

                    /*
                        현재 비교할 문자

                        i, j는 "길이" 기준이므로
                        실제 문자열 index로 접근할 때는 -1을 해준다.
                     */
                    char sc = s.charAt(i - 1);
                    char pc = p.charAt(j - 1);

                    /*
                        1. 현재 문자가 같거나
                           정규식 문자가 '.'인 경우

                        '.'은 아무 문자 1개와 매칭 가능하다.

                        현재 문자끼리 매칭되면
                        이전 문자들까지 매칭됐는지 확인하면 된다.

                        예:
                        s = "ab"
                        p = "ab"

                        마지막 b끼리 같으면
                        앞의 "a"와 "a"가 매칭됐는지 보면 된다.

                        dp[i][j] = dp[i - 1][j - 1]
                     */
                    if (pc == sc || pc == '.') {
                        dp[i][j] = dp[i - 1][j - 1];
                    }

                    /*
                        2. 현재 정규식 문자가 '*'인 경우

                        '*'는 바로 앞 문자와 한 세트이다.

                        예:
                        a*
                        b*
                        .*
                     */
                    else if (pc == '*') {

                        /*
                            (1) 앞 문자를 0번 사용

                            "앞 문자 + *"를 제거하는 것과 같다.

                            예:
                            s = "aab"
                            p = "c*a*b"

                            c*는 c를 0번 사용할 수 있으므로 제거 가능하다.
                         */
                        dp[i][j] = dp[i][j - 2];

                        /*
                            (2) 앞 문자를 1번 이상 사용

                            '*' 앞 문자가 현재 문자열 문자와 같거나
                            '*' 앞 문자가 '.'이면 가능하다.
                         */
                        char prev = p.charAt(j - 2);

                        /*
                            예:
                            s = "aa"
                            p = "a*"

                            현재 sc = 'a'
                            prev = 'a'

                            a*는 a를 여러 번 사용할 수 있으므로
                            "aa" vs "a*" 결과는
                            "a" vs "a*" 결과를 따라갈 수 있다.

                            그래서 dp[i - 1][j]를 확인한다.
                         */
                        if (prev == sc || prev == '.') {
                            dp[i][j] |= dp[i - 1][j];
                        }
                    }
                }
            }

            /*
                최종 답

                문자열 s 전체 m글자와
                정규식 p 전체 n글자가
                매칭되는지 여부를 반환한다.
             */
            return dp[m][n];
        }
    }

    public static void main(String[] args) {

        Solution sol = new Solution();

        /*
            [테스트 케이스]
         */
        System.out.println(sol.isMatch("aa", "a"));      // false
        System.out.println(sol.isMatch("aa", "a*"));     // true
        System.out.println(sol.isMatch("ab", ".*"));     // true
        System.out.println(sol.isMatch("aab", "c*a*b")); // true
        System.out.println(sol.isMatch("mississippi", "mis*is*p*.")); // false

        /*
            [빈 문자열 초기화 확인용]

            a*는 a를 0번 사용할 수 있으므로 제거 가능하다.
            하지만 마지막 b는 '*'가 없으므로 제거 불가능하다.

            따라서:
            "" vs "a*b" = false
         */
        System.out.println(sol.isMatch("", "a*b")); // false
    }
}